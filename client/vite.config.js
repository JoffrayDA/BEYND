import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';
import { VitePWA } from 'vite-plugin-pwa';

// Client is mobile-first PWA. Design-system lives one level up, so allow fs
// access to the repo root and let esbuild treat its .jsx as JSX.
export default defineConfig({
  plugins: [
    react({ include: /\.(jsx|js)$/ }),
    VitePWA({
      registerType: 'autoUpdate',
      includeAssets: ['favicon.svg', 'apple-touch-icon.png'],
      // API calls always go to the network, never to the app-shell fallback.
      workbox: { navigateFallbackDenylist: [/^\/api\//] },
      manifest: {
        name: 'BEYND',
        short_name: 'BEYND',
        description: 'Tes objectifs de vie, un Elo par catégorie',
        theme_color: '#1C1B19',
        background_color: '#1C1B19',
        display: 'standalone',
        start_url: '/',
        lang: 'fr',
        // Generated by scripts/icons.mjs.
        icons: [
          { src: 'icon-192.png', sizes: '192x192', type: 'image/png' },
          { src: 'icon-512.png', sizes: '512x512', type: 'image/png' },
          { src: 'icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
        ],
      },
    }),
  ],
  esbuild: { loader: 'jsx', include: /\.(jsx|js)$/ },
  optimizeDeps: { esbuildOptions: { loader: { '.js': 'jsx' } } },
  server: {
    fs: { allow: ['..'] },
    // API_PORT lets a second dev stack (tests) run beside the main one.
    proxy: { '/api': `http://localhost:${process.env.API_PORT || 8787}` },
  },
});
